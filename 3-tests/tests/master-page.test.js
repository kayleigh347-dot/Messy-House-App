import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const root=new URL('../',import.meta.url);
const read=name=>readFileSync(new URL(name,root),'utf8');

test('the copy-first master page preserves the shared compact layout pattern',()=>{
 const master=read('MASTER-PAGE.html');
 assert.match(master,/AGENT-ONLY MASTER PAGE/);
 assert.match(master,/DO NOT EDIT THIS FILE/);
 assert.match(master,/copy this complete section/i);
 assert.match(master,/class="page hide"/);
 assert.match(master,/class="settings-heading"/);
 assert.match(master,/class="folder-tabs"/);
 assert.match(master,/class="optional-section"/);
 assert.match(master,/do not add a title tagline/i);
});

test('fixed settings and help controls always use the existing settings views',()=>{
 const html=read('index.html'),features=read('features.js'),management=read('home-management.js'),styles=read('home-management.css');
 assert.match(html,/<aside class="static-utility-controls"/);
 assert.match(html,/id="simpleSettings"[^>]*>⚙︎<\/button>/);
 assert.match(html,/id="staticHelp"[^>]*>\?<\/button>/);
 assert.doesNotMatch(html,/id="simpleSettings"[^>]*hidden/);
 assert.match(features,/\$\('#staticHelp'\)\.onclick=.*data-settings-tab="help"/);
 assert.doesNotMatch(features,/\$\('#simpleSettings'\)\.hidden=/);
 assert.doesNotMatch(management,/simpleSettings.*\.hidden=/);
 assert.match(styles,/\.static-utility-controls\{position:fixed/);
});
